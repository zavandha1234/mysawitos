#!/usr/bin/env python3
# Generates logo.h : pohon sawit pixel art 80x80 (palette indexed)
import math
N=80
g=[[0]*N for _ in range(N)]
# 0 transparent,1 dark green,2 green,3 light green,4 brown,5 dark brown,6 orange,7 dark orange,8 yellow
def s(x,y,c):
    x=int(round(x));y=int(round(y))
    if 0<=x<N and 0<=y<N: g[y][x]=c
def disc(cx,cy,r,c):
    for y in range(int(cy-r-1),int(cy+r+2)):
        for x in range(int(cx-r-1),int(cx+r+2)):
            if (x-cx)**2+(y-cy)**2<=r*r+0.3: s(x,y,c)
for y in range(74,80):
    for x in range(14,67):
        if ((x-40)/27.0)**2+((y-79)/5.5)**2<=1: s(x,y,1 if y>76 else 2)
for y in range(77,33,-1):
    t=(77-y)
    cx=40+3*math.sin(t/14.0)
    w=2.6-1.0*t/44.0
    for x in range(int(cx-w-1),int(cx+w+2)):
        if abs(x-cx)<=w:
            c=5 if (abs(x-cx)>w-1.1 or t%5==0) else 4
            s(x,y,c)
cx0=40+3*math.sin(43/14.0); cy0=34
tips=[(3,44),(8,20),(24,5),(40,2),(56,5),(72,20),(77,44)]
for tx,ty in tips:
    qx=(cx0+tx)/2; qy=min(cy0,ty)-14
    for i in range(41):
        t=i/40.0
        px=(1-t)**2*cx0+2*(1-t)*t*qx+t*t*tx
        py=(1-t)**2*cy0+2*(1-t)*t*qy+t*t*ty
        dx=2*(1-t)*(qx-cx0)+2*t*(tx-qx); dy=2*(1-t)*(qy-cy0)+2*t*(ty-qy)
        L=math.hypot(dx,dy) or 1
        nx,ny=-dy/L,dx/L
        s(px,py,1); s(px,py+1,1)
        if i%2==1 and 2<i<40:
            ln=7*(1-t*0.7)
            for sgn in (1,-1):
                for k in range(1,int(ln)+1):
                    lx=px+sgn*nx*k*0.9; ly=py+sgn*ny*k*0.9+k*0.55
                    s(lx,ly,2 if k<ln-1.5 else 3)
    s(tx,ty,1)
disc(cx0,cy0+1,3,1); disc(cx0,cy0,2,2)
for fx,fy in [(cx0-5,40),(cx0+4,41),(cx0-1,44),(cx0-6,47),(cx0+5,47),(cx0-1,50),(cx0-4,53),(cx0+3,53)]:
    disc(fx,fy,3.2,6)
    for dx in (1,2,3):
        s(fx+dx-0.5,fy+3-(dx-1)*0.4,7); s(fx+3,fy+dx-2,7)
    s(fx-1,fy-1,8); s(fx-2,fy-1,8); s(fx-1,fy-2,8)
pal=[0x000000,0x1B5E20,0x2E9B3A,0x66CC55,0x8B5A2B,0x4A2E12,0xFF8C1A,0xB85500,0xFFD84D]
with open('logo.h','w') as f:
    f.write('/* My Sawit OS - logo pohon sawit 80x80 pixel art (generated by tools/gen_logo.py) */\n#ifndef LOGO_H\n#define LOGO_H\n')
    f.write('#define LOGO_W 80\n#define LOGO_H_PX 80\n')
    f.write('static const unsigned int logo_palette[9]={'+','.join('0x%06X'%c for c in pal)+'};\n')
    f.write('static const unsigned char logo_pixels[80*80]={\n')
    for y in range(N): f.write(','.join(str(v) for v in g[y])+',\n')
    f.write('};\n#endif\n')
try:
    from PIL import Image
    im=Image.new('RGB',(N,N))
    for y in range(N):
        for x in range(N): im.putpixel((x,y),pal[g[y][x]])
    im.resize((320,320),Image.NEAREST).save('/home/claude/logo_preview.png')
except Exception as e: print(e)
